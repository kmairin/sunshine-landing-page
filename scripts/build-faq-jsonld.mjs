// Rebuilds the FAQPage JSON-LD in index.html from the visible English FAQ,
// so the structured data never says something the page does not.
// Run after editing the FAQ: node scripts/build-faq-jsonld.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const file = join(dirname(fileURLToPath(import.meta.url)), '..', 'index.html');
const entities = { amp: '&', quot: '"', ntilde: 'ñ', aacute: 'á', eacute: 'é', iacute: 'í', oacute: 'ó', uacute: 'ú',
  iquest: '¿', iexcl: '¡', Aacute: 'Á', Uacute: 'Ú', mdash: '—', ndash: '–' };
const text = (html) => html.replace(/<[^>]+>/g, '')
  .replace(/&#39;/g, "'").replace(/&([a-zA-Z]+);/g, (m, n) => entities[n] ?? m)
  .replace(/\s+/g, ' ').trim();

const html = readFileSync(file, 'utf8');
const items = [...html.matchAll(/<details class="faq-item en">\s*<summary>([\s\S]*?)<\/summary>\s*<div class="faq-answer">([\s\S]*?)<\/div>\s*<\/details>/g)]
  .map((m) => ({
    '@type': 'Question',
    name: text(m[1]),
    acceptedAnswer: { '@type': 'Answer', text: text(m[2]) },
  }));

const faq = { '@context': 'https://schema.org', '@type': 'FAQPage', '@id': 'https://cclaundrysystem.com/#faq', mainEntity: items };
const block = `<!-- Schema: FAQPage (generated by scripts/build-faq-jsonld.mjs from the visible FAQ; do not edit by hand) -->
  <script type="application/ld+json">
${JSON.stringify(faq, null, 2).replace(/^/gm, '  ')}
  </script>`;

const re = /<!-- Schema: FAQPage[^>]*-->\s*<script type="application\/ld\+json">[\s\S]*?<\/script>/;
if (!re.test(html)) throw new Error('FAQPage block not found in index.html');
writeFileSync(file, html.replace(re, block));
console.log(`FAQPage written with ${items.length} questions`);
